/**
 * Generates the favicon and touch icon from the isotipo's pupil.
 *
 * TODO(brand-svg): provisional icons, derived from ISOTIPO_SHAPE (the bite
 * breaks the circle's edge, same as Imagotipo). Replace them when the official
 * SVGs arrive.
 *
 * Output (committed):
 * - public/favicon.svg          teal pupil, transparent background
 * - public/favicon.ico          16, 32 and 48 px PNGs inside an ICO container
 * - public/apple-touch-icon.png 180×180, teal pupil on navy, with margin
 *
 * Run once, with the isolated tools in .cache/tools (see README › Íconos):
 *   node .cache/tools/node_modules/.bin/tsx scripts/generate-icons.ts
 *
 * Playwright is resolved from .cache/tools at runtime (dynamic import), so the
 * app has no dependency on it and `tsc` never needs its types. It drives the
 * installed Google Chrome (`channel: 'chrome'`); nothing is downloaded.
 */

import { mkdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { ISOTIPO_SHAPE } from '../src/components/brand/geometry.js';
import { BRAND_COLORS } from '../src/styles/brandColors.js';

type Page = {
  setContent(html: string): Promise<void>;
  screenshot(options: { omitBackground: boolean; type: 'png' }): Promise<Uint8Array>;
};
type Browser = {
  newPage(options: { viewport: { width: number; height: number }; deviceScaleFactor: number }): Promise<Page>;
  close(): Promise<void>;
};
type Chromium = { launch(options: { channel: string; headless: boolean }): Promise<Browser> };
/** Playwright is CommonJS: a dynamic import exposes it under `default`. */
type PlaywrightModule = { default: { chromium: Chromium } };

const PUBLIC = fileURLToPath(new URL('../public/', import.meta.url));
const TOOLS = new URL('../.cache/tools/package.json', import.meta.url);

const ICO_SIZES = [16, 32, 48] as const;
const TOUCH_SIZE = 180;
/** Pupil diameter inside the touch icon; the rest is navy margin (30 px per side). */
const TOUCH_PUPIL = 120;

/** Pupil only: the isotipo's bitten circle, filled teal, on a transparent background. */
function faviconSvg(): string {
  return [
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">',
    '<!-- TODO(brand-svg): provisional, generated by scripts/generate-icons.ts -->',
    `<path d="${ISOTIPO_SHAPE.d}" fill="${BRAND_COLORS.teal}"/>`,
    '</svg>',
    '',
  ].join('\n');
}

/** Touch icon: navy square with the teal pupil centered. */
function touchSvg(): string {
  const offset = (TOUCH_SIZE - TOUCH_PUPIL) / 2;
  const scale = TOUCH_PUPIL / 100;
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${TOUCH_SIZE} ${TOUCH_SIZE}">`,
    `<rect width="${TOUCH_SIZE}" height="${TOUCH_SIZE}" fill="${BRAND_COLORS.navy}"/>`,
    `<g transform="translate(${offset} ${offset}) scale(${scale})"><path d="${ISOTIPO_SHAPE.d}" fill="${BRAND_COLORS.teal}"/></g>`,
    '</svg>',
  ].join('');
}

/** ICO container holding PNG images (supported by every current browser). */
function ico(images: ReadonlyArray<{ size: number; png: Uint8Array }>): Buffer {
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0); // reserved
  header.writeUInt16LE(1, 2); // type: icon
  header.writeUInt16LE(images.length, 4);
  let offset = 6 + 16 * images.length;
  const entries = images.map(({ size, png }) => {
    const entry = Buffer.alloc(16);
    entry.writeUInt8(size >= 256 ? 0 : size, 0); // width
    entry.writeUInt8(size >= 256 ? 0 : size, 1); // height
    entry.writeUInt8(0, 2); // palette colors
    entry.writeUInt8(0, 3); // reserved
    entry.writeUInt16LE(1, 4); // color planes
    entry.writeUInt16LE(32, 6); // bits per pixel
    entry.writeUInt32LE(png.length, 8);
    entry.writeUInt32LE(offset, 12);
    offset += png.length;
    return entry;
  });
  return Buffer.concat([header, ...entries, ...images.map(({ png }) => Buffer.from(png))]);
}

async function render(browser: Browser, svg: string, size: number): Promise<Uint8Array> {
  const page = await browser.newPage({ viewport: { width: size, height: size }, deviceScaleFactor: 1 });
  const sized = svg.replace('<svg ', `<svg width="${size}" height="${size}" `);
  await page.setContent(`<!doctype html><html><body style="margin:0;background:transparent">${sized}</body></html>`);
  return page.screenshot({ omitBackground: true, type: 'png' });
}

async function main(): Promise<void> {
  const playwrightPath = createRequire(TOOLS).resolve('playwright');
  const { chromium } = ((await import(pathToFileURL(playwrightPath).href)) as PlaywrightModule).default;
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  try {
    mkdirSync(PUBLIC, { recursive: true });
    const favicon = faviconSvg();
    writeFileSync(`${PUBLIC}favicon.svg`, favicon);
    const images = [];
    for (const size of ICO_SIZES) images.push({ size, png: await render(browser, favicon, size) });
    writeFileSync(`${PUBLIC}favicon.ico`, ico(images));
    writeFileSync(`${PUBLIC}apple-touch-icon.png`, await render(browser, touchSvg(), TOUCH_SIZE));
    console.log('public/favicon.svg, public/favicon.ico (16/32/48), public/apple-touch-icon.png (180)');
  } finally {
    await browser.close();
  }
}

await main();
